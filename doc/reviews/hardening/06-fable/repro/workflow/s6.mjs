import { start } from "./lib.mjs";
const backend = process.argv[2] ?? "c64u";
const h = await start();
if (backend === "vice") await h.call("c64_select_backend", { op: "select", backend: "vice" }, { show: 50 });
const G = (o) => h.call("c64_graphics", o, { show: 1500 });
const S = (o) => h.call("c64_sound", o, { show: 1500 });
const sprite = Array.from({length:63},(_,i)=> i%3===1?0x3c:0x00);
await G({ op: "render_sprite", sprite, x: 120, y: 100, color: 2 });
await G({ op: "render_sprite", sprite: "00".repeat(63), index: 1 });
await G({ op: "render_sprite", sprite: Buffer.alloc(63, 0xff).toString("base64") });
await G({ op: "render_petscii_text", text: "SCORE 000100", borderColor: 0, backgroundColor: 6 });
await G({ op: "render_petscii_art", prompt: "a small house", dryRun: true });
await G({ op: "get_display_state" });
await G({ op: "capture_frame", format: "png" });
await G({ op: "capture_frame" });
await S({ op: "note_on", voice: 1, note: "A4", waveform: "pulse" });
await S({ op: "analyze", request: "check the tone", durationSeconds: 1 });
await S({ op: "record_analyze", durationSeconds: 1 });
await S({ op: "note_off", voice: 1 });
await S({ op: "play_preset", preset: "fuer_elise", verify: false });
await S({ op: "silence_all" });
await h.stop(); process.exit(0);
