import { start } from "./lib.mjs";
const h = await start();
const C = (o, show=1500) => h.call("c64_config", o, { show });
await C({ op: "list" });
await C({ op: "get", category: "U64 Specific Settings" });
await C({ op: "get", category: "Turbo" });
await C({ op: "set", category: "U64 Specific Settings", item: "CPU Speed", value: "48 MHz" });
await C({ op: "get", category: "C64 and Cartridge Settings" });
await C({ op: "set", category: "C64 and Cartridge Settings", item: "RAM Expansion Unit", value: "Enabled" });
await C({ op: "set", category: "SID Sockets Configuration", item: "SID Socket 1", value: "Enabled" });
await C({ op: "batch_update", updates: { "U64 Specific Settings": { "Turbo Control": "Manual" } } });
await C({ op: "info" });
await C({ op: "version" });
const D = (o) => h.call("c64_disk", o, { show: 1500 });
await D({ op: "list_drives" });
await D({ op: "mount", drive: "a", image: "/Usb0/games/game.d64" });
await D({ op: "mount", drive: "drive8", image: "/Usb0/games/game.d64" });
await D({ op: "mount", drive: "8", image: "/tmp/h6/workflow/build/x.d64" });
await h.call("c64_stream", { op: "start", stream: "video", target: "127.0.0.1:11000" });
await h.call("c64_stream", { op: "stop", stream: "video" });
await h.call("c64_stream", { op: "start", stream: "video" });
await h.stop(); process.exit(0);
