import { start } from "./lib.mjs";
const h = await start();
await h.call("c64_select_backend", { op: "select", backend: "vice" }, { show: 50 });
const P = (o) => h.call("c64_program", o, { show: 1500 });
const D = (o) => h.call("c64_debug", o, { show: 1500 });
const S = (o) => h.call("c64_system", o, { show: 1500 });
await P({ op: "upload_run_asm", program: "*=$c000\nstart: ldx #0\nloop: inc counter\n inx\n jmp loop\ncounter: .byte 0\n" });
await D({ op: "create_checkpoint", address: "loop" });
await D({ op: "wait_for_state", timeoutMs: 1000 });
await D({ op: "get_registers" });
await D({ op: "get_registers", registers: [{ name: "PC" }, { name: "A" }] });
await D({ op: "step", count: 2 });
await D({ op: "get_monitor_state" });
await D({ op: "list_checkpoints" });
await D({ op: "continue_execution" });
await D({ op: "continue" });
await S({ op: "resume" });
await D({ op: "wait_for_state", expectedPC: "loop", timeoutMs: 1000 });
await D({ op: "step_return" });
await D({ op: "set_registers", writes: [{ name: "A", value: 5 }] });
await D({ op: "set_registers", writes: [{ name: "A", value: "$05" }] });
await D({ op: "delete_checkpoint", id: 1 });
await D({ op: "list_checkpoints" });
await h.call("c64_memory", { op: "read", address: "counter", length: 1 });
await h.stop(); process.exit(0);
