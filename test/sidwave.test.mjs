const EXAMPLE = `
# yaml-language-server: $schema=https://example.com/sidwave.schema.json
sidwave: 1.0
title: "Echoes of Tomorrow"
author: "Generated by MCP"
tempo: 92
mode: PAL
voices:
  - id: 1
    waveform: pulse
    patterns:
      A:
        type: arpeggio
        notes: [C3, E3, G3, B2]
        fx: { vibrato: { depth: 0.2, rate: 5 }, pwm_sweep: { speed: 1, depth: 64 } }
  - id: 2
    waveform: triangle
    patterns:
      B:
        groove: [C2, C2, G1, C2]
  - id: 3
    waveform: sawtooth
    patterns:
      C:
        groove: [C1, C1, C1, G0]

timeline:
  - section: Intro
    bars: 8
    layers: { v1: A, v2: B, v3: C }
`;

test("HARD01-032 sidwaveCompiler's hzToSidFrequency uses the SID's 24-bit phase accumulator", () => {
  // round(440 * 2^24 / 985248) = 7493 = $1D45 (PAL A4).
  assert.equal(hzToSidFrequency(440, "PAL"), 7493);
  // NTSC uses a different clock (1022727 Hz) but the same 2^24 divisor.
  assert.equal(hzToSidFrequency(440, "NTSC"), Math.round((440 * 16_777_216) / 1_022_727));
  assert.notEqual(hzToSidFrequency(440, "PAL"), Math.round((440 * 65_536) / 985_248));
});

test("SIDWAVE: compile to PRG and SID", () => {
  const doc = parseSidwave(EXAMPLE);
  const { prg } = compileSidwaveToPrg(doc);
  assert.ok(prg instanceof Buffer);
  // PRG load address may be $0801 (BASIC header) or $0810 (direct code)
  const load = prg.readUInt16LE(0);
  assert.ok(load === 0x0801 || load === 0x0810, `Unexpected load address ${load.toString(16)}`);
  const { sid } = compileSidwaveToSid(doc, prg);
  assert.ok(sid instanceof Buffer);
  assert.equal(sid.toString("ascii", 0, 4), "PSID");
  assert.ok(sid.length >= 124 + 2, `Unexpected SID length: ${sid.length}`);
});

// The player PRG ends with seven 1-byte tables per voice (freq lo/hi, pw lo/hi, ctrl, ad, sr), each one entry per frame.
function readFreqFrames(prg, frames) {
  const body = prg.subarray(2);
  const tableStart = body.length - (21 * frames);
  assert.ok(tableStart > 0, `PRG body (${body.length} bytes) is too short for ${frames}-frame tables`);
  return [0, 1, 2].map((voice) => {
    const lo = tableStart + (voice * 7 * frames);
    const hi = lo + frames;
    return Array.from({ length: frames }, (_, frame) => (body[hi + frame] << 8) | body[lo + frame]);
  });
}

function sidFreq(note) {
  return hzToSidFrequency(midiToHz(noteNameToMidi(note)), "PAL");
}

test("SIDWAVE: top-level format infers bar count from the timeline and compiles note data", () => {
  const doc = parseSidwave(EXAMPLE);
  assert.equal(doc.song.length_bars, 8);
  assert.equal(doc.song.tempo, 92);

  // 8 bars at 92 BPM exceed the 255-frame table cap.
  const [v1, v2, v3] = readFreqFrames(compileSidwaveToPrg(doc).prg, 255);
  assert.ok(v1.includes(sidFreq("E3")), "voice 1 frames should contain the arpeggio note E3");
  assert.ok(v2.includes(sidFreq("C2")), "voice 2 frames should contain the groove note C2");
  assert.ok(v3.includes(sidFreq("C1")), "voice 3 frames should contain the groove note C1");
});

test("SIDWAVE: an explicit top-level length_bars is honoured", () => {
  const doc = parseSidwave(EXAMPLE.replace("tempo: 92", "tempo: 92\nlength_bars: 3"));
  assert.equal(doc.song.length_bars, 3);
});

test("SIDWAVE: arpeggio, groove and motif patterns start on their first step", () => {
  // 120 BPM PAL: 25 frames per beat.
  const doc = parseSidwave({
    song: { title: "Order", tempo: 120, mode: "PAL" },
    voices: [
      { id: 1, waveform: "triangle", patterns: { A: { type: "arpeggio", notes: ["C4", "E4", "G4"] } } },
      { id: 2, waveform: "triangle", patterns: { B: { groove: ["C3", "G3"] } } },
      { id: 3, waveform: "triangle", patterns: { M: { motif: "0 4 7", length: 1 } } },
    ],
    timeline: [{ section: "S", bars: 2, layers: { v1: "A", v2: "B", v3: "M" } }],
  });
  const [v1, v2, v3] = readFreqFrames(compileSidwaveToPrg(doc).prg, 255);
  assert.deepEqual([v1[0], v1[24], v1[25], v1[50], v1[75]], ["C4", "C4", "E4", "G4", "C4"].map(sidFreq));
  assert.deepEqual([v2[0], v2[24], v2[25], v2[50]], ["C3", "C3", "G3", "C3"].map(sidFreq));
  assert.deepEqual([v3[0], v3[25], v3[50], v3[75]], ["C3", "E3", "G3", "C3"].map(sidFreq));
});

function parseWavPcm16(buffer) {
  // Very small parser for PCM16LE WAV files
  const view = new DataView(buffer.buffer, buffer.byteOffset, buffer.byteLength);
  if (buffer.toString("ascii", 0, 4) !== "RIFF" || buffer.toString("ascii", 8, 12) !== "WAVE") {
    throw new Error("Not a WAV file");
  }
  let offset = 12;
  let fmt = null;
  let data = null;
  while (offset + 8 <= buffer.length) {
    const id = buffer.toString("ascii", offset, offset + 4);
    const size = view.getUint32(offset + 4, true);
    offset += 8;
    if (id === "fmt ") {
      const audioFormat = view.getUint16(offset + 0, true);
      const numChannels = view.getUint16(offset + 2, true);
      const sampleRate = view.getUint32(offset + 4, true);
      const bitsPerSample = view.getUint16(offset + 14, true);
      fmt = { audioFormat, numChannels, sampleRate, bitsPerSample };
    } else if (id === "data") {
      data = buffer.subarray(offset, offset + size);
    }
    offset += size;
  }
  if (!fmt || !data) throw new Error("Invalid WAV: missing fmt or data chunk");
  if (fmt.audioFormat !== 1 || fmt.bitsPerSample !== 16) throw new Error("Expected PCM16 WAV");
  // Downmix if stereo
  const samples = new Float32Array(data.length / 2 / fmt.numChannels);
  let outIdx = 0;
  for (let i = 0; i < data.length; i += 2 * fmt.numChannels) {
    let acc = 0;
    for (let ch = 0; ch < fmt.numChannels; ch += 1) {
      const s = data.readInt16LE(i + ch * 2);
      acc += s / 32768;
    }
    samples[outIdx++] = acc / fmt.numChannels;
  }
  return { samples, sampleRate: fmt.sampleRate };
}

test("SIDWAVE -> SID -> WAV via sidplayfp, then analyze", async (t) => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "sidwave-"));
  const sidPath = path.join(tmp, "song.sid");
  const wavPath = path.join(tmp, "song.wav");

  const doc = parseSidwave(EXAMPLE);
  const { prg, entryAddress } = compileSidwaveToPrg(doc);
  const { sid } = compileSidwaveToSid(doc, prg, { entryAddress });
  fs.writeFileSync(sidPath, sid);

  try {
  const mode = (doc.mode || "ntsc").toLowerCase() === "pal" ? "pal" : "ntsc";
  const res = await runSidToWav({ sidPath, wavPath, mode, limitCycles: 800_000 });
    assert.equal(res.exitCode, 0);
    assert.ok(fs.existsSync(wavPath), "WAV not created");
    const stat = fs.statSync(wavPath);
    assert.ok(stat.size > 0, "WAV is empty");
    assert.equal(res.wavInfo.sampleRate, 44100, "expected 44.1kHz sample rate");
    assert.equal(res.wavInfo.bitsPerSample, 16, "expected 16-bit PCM");

    const wavBuf = fs.readFileSync(wavPath);
    const { samples, sampleRate } = parseWavPcm16(wavBuf);
    const analysis = await analyzePcmForTest(samples, sampleRate, EXAMPLE);
    assert.ok(analysis?.analysis?.voices?.[0]?.detected_notes?.length >= 1, "no notes detected in WAV analysis");
  } catch (e) {
    if (e && typeof e === "object" && (e instanceof SidplayExecutionError)) {
      if (e.exitCode === 127) {
        t.skip("sidplayfp not installed (exit 127)");
        return;
      }
      // Log diagnostics for CI analysis
      console.error("sidplayfp command:", e.command);
      if (e.stderrFirst) console.error("stderr(first):\n" + e.stderrFirst);
      if (e.stderrLast) console.error("stderr(last):\n" + e.stderrLast);
    }
    throw e;
  }
});
