#!/usr/bin/env bash
# Produces the standalone SIDWAVE repository from the packages/ directory of this repository, with the history of
# the moved files, and proves that the result builds, tests, packs and installs on its own.
#
#   scripts/split-sidwave-repo.sh [--ref <git ref>] [--out <dir>] [--evidence <file>] [--no-proof] [--keep-work]
#
#   --ref       commit to split (default HEAD). It must be reachable from a local branch.
#   --out       target directory (default /home/chris/dev/c64/sidwave). An empty or missing directory is used as is,
#               a previous output of this script (git repository with config sidwave.splitOutput=true) is replaced,
#               anything else is refused.
#   --evidence  JSON file for the proof result (default evidence/sidwave-split-proof.json in this repository).
#   --no-proof  only split; skip install, build, tests, coverage, pack and consumer check.
#
# How the history is carried over (git filter-repo, run on a throw-away clone):
#   - Files below packages/ keep their history; the packages/ prefix is removed, so packages/ becomes the root.
#   - Files that were moved into packages/ from other paths (renames and copies, found with git's rename and copy
#     detection on every commit that adds a packages/ file from outside packages/) also carry their earlier history,
#     under the new path. This applies only to commits before the move: afterwards the old paths hold re-export
#     shims and generated copies that are not part of the standalone repository.
#   - The standalone repository gets one more commit with the package-lock.json generated by the proof, so that
#     `npm ci` works in its CI. The lock file is never written by hand; rerunning the script regenerates it.
# Nothing is pushed anywhere and no GitHub repository is created.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
REF=HEAD
OUT=/home/chris/dev/c64/sidwave
EVIDENCE="$REPO_ROOT/evidence/sidwave-split-proof.json"
PROOF=1
KEEP=0

while [ $# -gt 0 ]; do
  case "$1" in
    --ref) REF="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    --evidence) EVIDENCE="$2"; shift 2 ;;
    --no-proof) PROOF=0; shift ;;
    --keep-work) KEEP=1; shift ;;
    -h|--help) sed -n '2,22p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

for tool in git git-filter-repo python3 npm node; do
  command -v "$tool" >/dev/null || { echo "missing tool: $tool" >&2; exit 2; }
done
[ "$PROOF" = 0 ] || command -v bun >/dev/null || { echo "missing tool: bun (use --no-proof to skip the proof)" >&2; exit 2; }

OUT="$(python3 -c 'import os,sys; print(os.path.abspath(sys.argv[1]))' "$OUT")"
EVIDENCE="$(python3 -c 'import os,sys; print(os.path.abspath(sys.argv[1]))' "$EVIDENCE")"
case "$OUT/" in "$REPO_ROOT"/*) echo "refusing an output directory inside the source repository" >&2; exit 2 ;; esac

# Check the target before doing any work.
if [ -e "$OUT" ]; then
  if [ -d "$OUT" ] && [ -z "$(ls -A "$OUT")" ]; then :
  elif [ -d "$OUT/.git" ] && [ "$(git -C "$OUT" config --local --get sidwave.splitOutput || true)" = true ]; then :
  else
    echo "refusing to overwrite $OUT: it is not empty and not the output of a previous split" >&2
    exit 2
  fi
fi

SHA="$(git -C "$REPO_ROOT" rev-parse --verify "$REF^{commit}")"
if [ -n "$(git -C "$REPO_ROOT" status --porcelain -- packages scripts/split-sidwave-repo.sh)" ]; then
  echo "warning: uncommitted changes below packages/ are not part of $SHA" >&2
fi
COMMON_GIT_DIR="$(git -C "$REPO_ROOT" rev-parse --path-format=absolute --git-common-dir)"

WORK="$(mktemp -d "${TMPDIR:-/tmp}/sidwave-split.XXXXXX")"
cleanup() { [ "$KEEP" = 1 ] && echo "work directory kept: $WORK" >&2 || rm -rf "$WORK"; }
trap cleanup EXIT

echo "== cloning $SHA"
git clone --quiet --no-local --no-checkout "$COMMON_GIT_DIR" "$WORK/clone"
git -C "$WORK/clone" update-ref refs/heads/main "$SHA"
git -C "$WORK/clone" symbolic-ref HEAD refs/heads/main
git -C "$WORK/clone" rev-parse --verify -q main >/dev/null

echo "== deriving the old-to-new path mapping"
python3 - "$WORK/clone" "$WORK/mapping.json" <<'PY'
import json, subprocess, sys
clone, out = sys.argv[1:3]
def git(*args):
    return subprocess.run(["git", "-C", clone, *args], check=True, capture_output=True, text=True).stdout
moves = {}      # (parent of the move commit, old path) -> set of new paths (without the packages/ prefix)
for commit in git("log", "--format=%H", "main", "--", "packages/").split():
    parents = git("rev-list", "--parents", "-n", "1", commit).split()[1:]
    if not parents:
        continue
    diff = git("diff-tree", "--no-commit-id", "-r", "-M50%", "-C50%", "--find-copies-harder", "--name-status", parents[0], commit)
    for line in diff.splitlines():
        fields = line.split("\t")
        if fields[0][0] in "RC" and not fields[1].startswith("packages/") and fields[2].startswith("packages/"):
            moves.setdefault((parents[0], fields[1]), set()).add(fields[2][len("packages/"):])
# An old path is mapped only in commits before the commit that moved it (ancestors of that commit's parent). Later
# commits touching the old path (shims, generated copies) are not part of the standalone repository.
ancestors = {}
entries = []
for (parent, old), new in sorted(moves.items()):
    if parent not in ancestors:
        ancestors[parent] = set(git("rev-list", parent).split())
    entries.append({"old": old, "new": sorted(new), "before": parent})
json.dump({"before": {k: sorted(v) for k, v in ancestors.items()}, "moves": entries}, open(out, "w"))
print(f"{len(entries)} moved or copied source paths from {len(ancestors)} move commits")
PY

echo "== filtering history"
# The callback keeps only packages/ files (prefix removed) and, in commits before the move of that path, the old paths of moved
# files (mapped to their new paths). A path may map to several new paths (a copied LICENSE). Everything else is dropped.
cat > "$WORK/callback.py" <<'PY'
import json, os
if "_split" not in globals():
    _split = json.load(open(os.environ["SIDWAVE_SPLIT_MAPPING"]))
    _before = {k: set(v) for k, v in _split["before"].items()}
    _moves = {}
    for entry in _split["moves"]:
        _moves.setdefault(entry["old"].encode(), []).append((entry["before"], [n.encode() for n in entry["new"]]))
_id = commit.original_id.decode()
changes = []
seen = set()
for change in commit.file_changes:
    name = change.filename
    if name.startswith(b"packages/"):
        targets = [name[len(b"packages/"):]]
    else:
        targets = []
        for parent, new in _moves.get(name, []):
            if _id in _before[parent]:
                targets.extend(new)
    for target in targets:
        if target in seen:
            continue
        seen.add(target)
        changes.append(FileChange(change.type, target, change.blob_id, change.mode))
commit.file_changes = changes
PY
(cd "$WORK/clone" && SIDWAVE_SPLIT_MAPPING="$WORK/mapping.json" git filter-repo --force --refs main \
  --commit-callback "$(cat "$WORK/callback.py")" >"$WORK/filter-repo.log" 2>&1) || { tail -20 "$WORK/filter-repo.log" >&2; exit 1; }

echo "== writing the repository"
git clone --quiet --no-local --single-branch --branch main "$WORK/clone" "$WORK/result"
git -C "$WORK/result" remote remove origin
git -C "$WORK/result" config --local sidwave.splitOutput true
COMMITS="$(git -C "$WORK/result" rev-list --count HEAD)"
echo "$COMMITS commits, $(git -C "$WORK/result" ls-files | wc -l) files"
# The tree of the new HEAD must be exactly the tree of packages/ at the source commit.
if [ "$(git -C "$WORK/result" rev-parse 'HEAD^{tree}')" != "$(git -C "$REPO_ROOT" rev-parse "$SHA:packages")" ]; then
  echo "the split tree differs from packages/ at $SHA" >&2
  exit 1
fi
echo "tree identical to packages/ at the source commit"

# History checks: authorship, dates and subjects of the commits that touched a moved file before the move must be
# present under the new path; git log --follow must reach the same commits.
python3 - "$REPO_ROOT" "$SHA" "$WORK/result" "$WORK/history.json" <<'PY'
import json, subprocess, sys
repo, sha, result, out = sys.argv[1:5]
def git(cwd, *args):
    return subprocess.run(["git", "-C", cwd, *args], check=True, capture_output=True, text=True).stdout
checks = []
pairs = [("src/sidwaveCompiler.ts", "sidwave/src/sidwaveCompiler.ts"), ("src/sidwave.ts", "sidwave/src/sidwave.ts"),
         ("src/tools/translation/assembler.ts", "asm6502/src/assembler.ts"), ("data/sound/sidwave.md", "sidwave/data/sound/sidwave.md")]
fmt = "--format=%an|%ae|%at|%s"
ok = True
for old, new in pairs:
    # Commits that touched the old path, from the first one up to the move, in the source repository.
    original = {l for l in git(repo, "log", fmt, sha, "--", old).splitlines()}
    carried = set(git(result, "log", fmt, "--", new).splitlines())
    followed = git(result, "log", "--follow", fmt, "--", new).splitlines()
    missing = sorted(original - carried)
    # The source log also lists the move commit and later edits of shims, which are not part of the new history.
    mapped_before = [l for l in original if l in carried]
    oldest = min((int(l.split("|")[2]) for l in carried), default=None)
    entry = {"old": old, "new": new, "source_commits_for_old_path": len(original), "carried": len(mapped_before),
             "not_carried": missing[:5], "log_follow_commits": len(followed), "oldest_author_time": oldest,
             "authors": sorted({l.split("|")[0] for l in carried})}
    # --follow omits merge commits that plain log lists, so compare sets and the oldest commit, not counts.
    follow_oldest = min(int(l.split("|")[2]) for l in followed) if followed else None
    entry["follow_oldest_author_time"] = follow_oldest
    entry["ok"] = (not missing) and set(followed) <= carried and follow_oldest == oldest and len(entry["authors"]) >= 1
    ok &= entry["ok"]
    checks.append(entry)
json.dump({"ok": ok, "files": checks}, open(out, "w"), indent=2)
print("history checks:", "ok" if ok else "FAILED")
for c in checks:
    print(f"  {c['new']}: {c['carried']}/{c['source_commits_for_old_path']} source commits carried, {c['log_follow_commits']} by --follow, authors {', '.join(c['authors'])}")
sys.exit(0 if ok else 1)
PY

# --- proof ---------------------------------------------------------------------------------------------------------
STEPS="$WORK/steps.jsonl"
: > "$STEPS"
step() { # name command...
  local name="$1"; shift
  local log="$WORK/step-$name.log" start end code=0
  echo "== proof: $name"
  start=$(date +%s)
  ( cd "$PROOFDIR" && "$@" ) >"$log" 2>&1 || code=$?
  end=$(date +%s)
  python3 - "$name" "$code" "$((end - start))" "$log" >>"$STEPS" <<'PY'
import json, sys
name, code, secs, log = sys.argv[1:5]
print(json.dumps({"step": name, "exit": int(code), "seconds": int(secs), "tail": open(log, errors="replace").read()[-600:] if code != "0" else ""}))
PY
  if [ "$code" != 0 ]; then tail -25 "$log" >&2; return "$code"; fi
}

PROOF_OK=true
if [ "$PROOF" = 1 ]; then
  PROOFDIR="$WORK/proof"
  mkdir "$PROOFDIR"
  git -C "$WORK/result" archive HEAD | tar -x -C "$PROOFDIR"
  {
    step install npm install --no-audit --no-fund &&
    step build npm run build &&
    step test-node npm test &&
    step test-bun npm run test:bun &&
    step coverage npm run coverage &&
    step pack npm pack --workspaces --pack-destination "$WORK/packs" &&
    step consumer node scripts/check-consumer.mjs --out "$WORK/consumer.json" &&
    step clean-ci-install bash -c 'rm -rf node_modules */node_modules */dist */coverage && npm ci --no-audit --no-fund && npm run build'
  } || PROOF_OK=false
  if [ "$PROOF_OK" = true ]; then
    # The lock file produced by `npm install` becomes the last commit of the standalone repository.
    cp "$PROOFDIR/package-lock.json" "$WORK/result/package-lock.json"
    git -C "$WORK/result" add package-lock.json
    git -C "$WORK/result" -c user.name="sidwave split" -c user.email="split@localhost" commit --quiet -m "Add package-lock.json generated by the split proof"
  fi
fi

PACKS="$WORK/pack-lists.json"
if [ "$PROOF" = 1 ] && [ -d "$WORK/packs" ]; then
  python3 - "$WORK/packs" >"$PACKS" <<'PY'
import json, subprocess, sys, glob, os
d = sys.argv[1]
out = {}
for t in sorted(glob.glob(os.path.join(d, "*.tgz"))):
    names = subprocess.run(["tar", "-tzf", t], check=True, capture_output=True, text=True).stdout.split()
    out[os.path.basename(t)] = sorted(n[len("package/"):] for n in names)
print(json.dumps(out, indent=1))
PY
else
  echo '{}' >"$PACKS"
fi

mkdir -p "$(dirname "$EVIDENCE")"
python3 - "$WORK" "$SHA" "$OUT" "$COMMITS" "$PROOF_OK" "$PROOF" "$EVIDENCE" <<'PY'
import json, os, subprocess, sys, datetime
work, sha, out, commits, proof_ok, proof, evidence = sys.argv[1:8]
def load(name, default):
    p = os.path.join(work, name)
    return json.load(open(p)) if os.path.exists(p) else default
steps = [json.loads(l) for l in open(os.path.join(work, "steps.jsonl")) if l.strip()]
result = {
    "source_ref_commit": sha, "output": out, "commit_count": int(commits),
    "tree_equals_packages_at_source": True,
    "head_after_split": subprocess.run(["git", "-C", os.path.join(work, "result"), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip(),
    "generated_at": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
    "history": load("history.json", {}), "proof_run": proof == "1", "proof_ok": proof_ok == "true" if proof == "1" else None,
    "steps": steps, "consumer": load("consumer.json", None), "pack_contents": load("pack-lists.json", {}),
}
json.dump(result, open(evidence, "w"), indent=2)
PY

if [ "$PROOF" = 1 ] && [ "$PROOF_OK" != true ]; then
  echo "proof FAILED; the repository at $OUT was not written (details in $EVIDENCE)" >&2
  exit 1
fi

# Replace the target only after everything succeeded.
if [ -e "$OUT" ]; then rm -rf "$OUT"; fi
mkdir -p "$(dirname "$OUT")"
mv "$WORK/result" "$OUT"
echo "== done: $OUT ($(git -C "$OUT" rev-list --count HEAD) commits); evidence: $EVIDENCE"
